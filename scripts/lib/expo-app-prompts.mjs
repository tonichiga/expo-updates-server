import fs from "node:fs";
import path from "node:path";

const TEXT = {
  ru: {
    app: "Путь к корню Expo-приложения",
    certificate: "Путь к public certificate",
    serverUrl: "URL OTA-сервера",
    channel: "Channel",
    runtimeVersion: "Runtime version",
    platform: "Платформа: all, ios или android",
    force: "Перезаписывать ранее созданные CLI-файлы? [y/N]",
    confirm: "Продолжить настройку и запустить expo prebuild? [y/N]",
    cancelled: "Настройка отменена.",
    summary: "Будут применены настройки:",
  },
  en: {
    app: "Expo application root path",
    certificate: "Public certificate path",
    serverUrl: "OTA server URL",
    channel: "Channel",
    runtimeVersion: "Runtime version",
    platform: "Platform: all, ios or android",
    force: "Overwrite files previously generated by the CLI? [y/N]",
    confirm: "Continue and run expo prebuild? [y/N]",
    cancelled: "Configuration cancelled.",
    summary: "The following configuration will be applied:",
  },
};

function readAppDefaults(appRoot) {
  try {
    const appJson = JSON.parse(
      fs.readFileSync(path.join(appRoot, "app.json"), "utf8"),
    );
    return {
      channel:
        appJson.expo?.updates?.requestHeaders?.["expo-channel-name"] ||
        appJson.expo?.extra?.updateChannel ||
        "development",
      runtimeVersion:
        typeof appJson.expo?.runtimeVersion === "string"
          ? appJson.expo.runtimeVersion
          : "",
      serverUrl: appJson.expo?.updates?.url || "http://localhost:3000",
    };
  } catch {
    return {
      channel: "development",
      runtimeVersion: "",
      serverUrl: "http://localhost:3000",
    };
  }
}

async function askWithDefault(ask, question, defaultValue = "") {
  const suffix = defaultValue ? ` (${defaultValue})` : "";
  const answer = (await ask(`${question}${suffix}: `)).trim();
  return answer || defaultValue;
}

function isYes(value) {
  return ["y", "yes", "д", "да"].includes(value.trim().toLowerCase());
}

export async function collectInteractiveOptions(
  initialOptions,
  {
    ask,
    serverRoot = process.cwd(),
    log = console.log,
  },
) {
  const languageAnswer = await askWithDefault(
    ask,
    "Язык / Language [ru/en]",
    "ru",
  );
  const language = languageAnswer.toLowerCase() === "en" ? "en" : "ru";
  const text = TEXT[language];
  const options = { ...initialOptions };

  options.app = await askWithDefault(ask, text.app, options.app || "");
  const appRoot = path.resolve(options.app);
  const appDefaults = readAppDefaults(appRoot);

  options.certificate = await askWithDefault(
    ask,
    text.certificate,
    options.certificate ||
      path.join(
        serverRoot,
        "local-certificates",
        "code-signing-certificate.pem",
      ),
  );
  options.serverUrl = await askWithDefault(
    ask,
    text.serverUrl,
    options.serverUrl || appDefaults.serverUrl,
  );
  options.channel = await askWithDefault(
    ask,
    text.channel,
    options.channel || appDefaults.channel,
  );
  options.runtimeVersion = await askWithDefault(
    ask,
    text.runtimeVersion,
    options.runtimeVersion || appDefaults.runtimeVersion,
  );
  options.platform = await askWithDefault(
    ask,
    text.platform,
    options.platform || "all",
  );

  if (options.force !== true) {
    options.force = isYes(await ask(`${text.force}: `));
  }

  log("");
  log(text.summary);
  log(`  app: ${path.resolve(options.app)}`);
  log(`  certificate: ${path.resolve(options.certificate)}`);
  log(`  server: ${options.serverUrl}`);
  log(`  channel: ${options.channel}`);
  log(`  runtime: ${options.runtimeVersion}`);
  log(`  platform: ${options.platform}`);
  log(`  overwrite: ${options.force ? "yes" : "no"}`);
  log("");

  const confirmed = isYes(await ask(`${text.confirm}: `));
  if (!confirmed) {
    throw new Error(text.cancelled);
  }

  return options;
}
